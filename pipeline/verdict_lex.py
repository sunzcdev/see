def level_of(dom, txt):
    """返回该域命中的最高等级；无命中返回 None。在原文（未打码）上做最长优先匹配。"""
    if dom not in LEVEL or not txt:
        return None
    entries = [(w, lv) for lv, ws in LEVEL[dom] for w in ws]
    entries.sort(key=lambda x: -len(x[0]))
    t = txt
    best = None
    for w, lv in entries:
        i = t.find(w)
        if i >= 0:
            if best is None or lv > best:
                best = lv
            t = t[:i] + '□' * len(w) + t[i + len(w):]
    return best


def strip_noise(t):
    t = re.sub(r'["“][^"”]{4,60}["”]', '', t)                 # 诀言诗句
    t = re.sub(r'[（(][^）)]{0,40}(?:阴|阳)年[^）)]{0,20}[）)]', '', t)
    t = re.sub(r'(?:农历|公历)\s*\d{2,4}[-年][^\s|｜，。；;]{0,12}', '', t)
    t = re.sub(r'\d{4}[-/]\d{1,2}[-/]?\d{0,2}', '', t)
    t = re.sub(r'[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]\s*\d{1,3}', '', t)   # 大运序列
    t = re.sub(r'\*{1,2}', '', t)
    return t.strip(' ：:|-—✅')


