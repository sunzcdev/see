def classify(txt):
    if not txt:
        return ''
    # ① 先消解否定（"不缺钱"→吉），把否定短语整体挖掉并用占位符顶替
    pos_forced = []
    t = txt
    for m in re.finditer(r'不(离婚|贫贱|贫穷|贫寒|缺钱|愁吃穿|病)|无(?:大病|灾|碍)', t):
        pos_forced.append(m.group(1))
        t = t.replace(m.group(0), '□')
    # ② 最长优先 + 命中即吞掉该跨度（防子串误伤）
    pairs = []
    for dom, pols in LEX.items():
        for pol, words in pols.items():
            for w in words:
                pairs.append((w, dom, pol))
    pairs.sort(key=lambda x: -len(x[0]))
    d = defaultdict(lambda: {"吉": [], "凶": []})
    for w, dom, pol in pairs:
        i = t.find(w)
        if i >= 0:
            d[dom][pol].append(w)
            t = t[:i] + '□' * len(w) + t[i + len(w):]
    for w in pos_forced:
        for dom in ("财", "寿元健康", "婚姻"):
            if w in ("离婚", "贫贱", "贫穷", "贫寒"):
                if dom == "婚姻" and w == "离婚":
                    d[dom]["吉"].append("不离婚")
                if dom == "财" and w in ("贫贱", "贫穷", "贫寒"):
                    d[dom]["吉"].append("不" + w)
    out = {}
    for dom, p in d.items():
        g, x = p["吉"], p["凶"]
        if not g and not x:
            continue
        item = {"pol": "吉" if g and not x else "凶" if x and not g else "混",
                "ev": (g + x)[:4]}
        lv = level_of(dom, txt)
        if lv is not None:
            item["lvl"] = lv
        out[dom] = item
    return json.dumps(out, ensure_ascii=False) if out else ''
